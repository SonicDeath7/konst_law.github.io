export async function askLegalAI(
  userQuery: string,
  history: { role: 'user' | 'assistant'; content: string }[] = []
): Promise<{ text: string; source: 'gemini' | 'knowledge_base' }> {
  const cleanQuery = userQuery.trim();
  if (!cleanQuery) {
    return {
      text: "Пожалуйста, введите ваш юридический вопрос.",
      source: 'knowledge_base'
    };
  }

  // 1. Try server-side API first
  try {
    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        query: cleanQuery,
        history: history.slice(-6)
      })
    });

    if (response.ok) {
      const data = await response.json();
      if (data.answer) {
        return {
          text: data.answer,
          source: data.source || 'gemini'
        };
      }
    }
  } catch (_err) {
    // API not reachable (static hosting like GitHub Pages / GitVerse or network issue)
  }

  // 2. Client-side Smart Knowledge Base & Pattern Matcher
  const lower = cleanQuery.toLowerCase();

  for (const item of KNOWLEDGE_BASE) {
    const match = item.keywords.some((k) => lower.includes(k));
    if (match) {
      return {
        text: item.answer,
        source: 'knowledge_base'
      };
    }
  }

  // Fallback structured guide
  return {
    text: `### Первичные рекомендации по вашему вопросу

Благодарю за обращение! По законодательству РФ для точного решения вашей ситуации необходимо учесть конкретные обстоятельства и имеющиеся документы.

1. **Основные шаги:**
   - Сохраните все относящиеся к делу документы (договоры, переписку, квитанции, акты, претензии).
   - Проверьте сроки обращения (общий срок исковой давности по ст. 196 ГК РФ составляет 3 года, но по трудовым, страховым и административным делам сроки значительно короче — от 1 месяца до 1 года).
   - При нарушении ваших прав первым этапом обычно является составление мотивированной досудебной претензии с подтверждением отправки.

2. **Запись на подробный правовой анализ:**
   - Поскольку каждый юридический спор имеет скрытые риски и процессуальные нюансы, рекомендуем доверить ведение дела профессиональному юристу.
   - Вы можете оставить заявку на консультацию к **Мирошину Константину Алексеевичу** через кнопку ниже или по телефону **+7 (910) 700-08-01**.`,
    source: 'knowledge_base'
  };
}
